CREATE TABLE IF NOT EXISTS search_log (
  log_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_no    BIGINT       NULL REFERENCES member (member_no) ON DELETE SET NULL,
  keyword      VARCHAR(100) NOT NULL,
  result_count INT          NOT NULL DEFAULT 0,
  searched_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_search_time ON search_log (searched_at);
CREATE INDEX IF NOT EXISTS idx_search_member ON search_log (member_no, searched_at);

CREATE TABLE IF NOT EXISTS restock_request (
  member_no    BIGINT      NOT NULL REFERENCES member (member_no) ON DELETE CASCADE,
  book_id      VARCHAR(20) NOT NULL REFERENCES book (book_id) ON DELETE CASCADE,
  requested_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (member_no, book_id)
);

CREATE TABLE IF NOT EXISTS notification (
  notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_no       BIGINT       NOT NULL REFERENCES member (member_no) ON DELETE CASCADE,
  message         VARCHAR(200) NOT NULL,
  link            VARCHAR(200) NULL,
  created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read_at         TIMESTAMP    NULL
);
CREATE INDEX IF NOT EXISTS idx_noti_member ON notification (member_no, read_at);

CREATE TABLE IF NOT EXISTS book_pick (
  pick_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id    VARCHAR(20)  NOT NULL REFERENCES book (book_id) ON DELETE CASCADE,
  comment    VARCHAR(200) NOT NULL,
  picked_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS taste_result (
  member_no BIGINT      NOT NULL PRIMARY KEY REFERENCES member (member_no) ON DELETE CASCADE,
  bear_type VARCHAR(20) NOT NULL,
  taken_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS attendance (
  member_no  BIGINT NOT NULL REFERENCES member (member_no) ON DELETE CASCADE,
  check_date DATE   NOT NULL,
  PRIMARY KEY (member_no, check_date)
);

