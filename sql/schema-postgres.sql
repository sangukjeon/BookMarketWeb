DROP TABLE IF EXISTS review, wishlist, order_item, orders, coupon, book, member CASCADE;

-- 회원 (자체 가입 + 구글/네이버/카카오 소셜 + 관리자)
CREATE TABLE member (
  member_no     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login_id      VARCHAR(50)  NOT NULL,
  password_hash VARCHAR(100) NULL,           -- 소셜 회원은 비어 있음
  salt          VARCHAR(50)  NULL,
  name          VARCHAR(50)  NOT NULL,
  phone         VARCHAR(20)  NULL,
  address       VARCHAR(200) NULL,
  email         VARCHAR(100) NULL,
  provider      VARCHAR(10)  NOT NULL DEFAULT 'LOCAL',   -- LOCAL / GOOGLE / NAVER / KAKAO
  provider_id   VARCHAR(100) NULL,
  role          VARCHAR(10)  NOT NULL DEFAULT 'USER',    -- USER / ADMIN
  status        VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',  -- ACTIVE / SUSPENDED (정지되면 로그인 불가)
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_member_login UNIQUE (login_id),
  CONSTRAINT uk_member_social UNIQUE (provider, provider_id)
);

-- 도서 (직접 등록 LOCAL + 카카오 책 검색으로 본 책 KAKAO)
CREATE TABLE book (
  book_id      VARCHAR(20)   PRIMARY KEY,    -- ISBN
  name         VARCHAR(200)  NOT NULL,
  unit_price   INT           NOT NULL,
  author       VARCHAR(200)  NULL,
  description  VARCHAR(1000) NULL,
  category     VARCHAR(50)   NULL,
  release_date VARCHAR(10)   NULL,
  image        VARCHAR(300)  NULL,           -- 파일 이름 또는 http 주소
  publisher    VARCHAR(100)  NULL,
  source       VARCHAR(10)   NOT NULL DEFAULT 'LOCAL'   -- LOCAL / KAKAO
);

-- 쿠폰 (정률 RATE: value=% / 정액 AMOUNT: value=원)
CREATE TABLE coupon (
  code         VARCHAR(20)  PRIMARY KEY,
  name         VARCHAR(50)  NOT NULL,
  type         VARCHAR(10)  NOT NULL,        -- RATE / AMOUNT
  value        INT          NOT NULL,
  min_amount   INT          NOT NULL DEFAULT 0,
  max_discount INT          NULL,            -- 정률 쿠폰의 최대 할인액
  active       BOOLEAN      NOT NULL DEFAULT TRUE
);

-- 주문 (영수증 머리)
CREATE TABLE orders (
  order_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_no      BIGINT       NOT NULL REFERENCES member (member_no),
  receiver_name  VARCHAR(50)  NOT NULL,
  receiver_phone VARCHAR(20)  NOT NULL,
  address        VARCHAR(200) NOT NULL,
  item_total     INT          NOT NULL,
  discount       INT          NOT NULL DEFAULT 0,
  shipping_fee   INT          NOT NULL DEFAULT 0,
  pay_amount     INT          NOT NULL,
  coupon_code    VARCHAR(20)  NULL REFERENCES coupon (code),
  status         VARCHAR(10)  NOT NULL DEFAULT 'ORDERED',   -- ORDERED / CANCELLED
  ordered_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cancelled_at   TIMESTAMP    NULL
);
CREATE INDEX idx_orders_member ON orders (member_no);
CREATE INDEX idx_orders_status ON orders (status, ordered_at);

-- 주문 항목 (주문 당시 가격을 따로 저장)
CREATE TABLE order_item (
  order_id   BIGINT       NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
  book_id    VARCHAR(20)  NOT NULL REFERENCES book (book_id),
  book_name  VARCHAR(200) NOT NULL,
  unit_price INT          NOT NULL,
  quantity   INT          NOT NULL,
  line_total INT          NOT NULL,
  PRIMARY KEY (order_id, book_id)
);

-- 찜 (회원 N : M 도서)
CREATE TABLE wishlist (
  member_no  BIGINT      NOT NULL REFERENCES member (member_no) ON DELETE CASCADE,
  book_id    VARCHAR(20) NOT NULL REFERENCES book (book_id) ON DELETE CASCADE,
  created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (member_no, book_id)
);

-- 리뷰 (구매한 회원만, 책 1권에 1개)
CREATE TABLE review (
  review_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_no  BIGINT       NOT NULL REFERENCES member (member_no) ON DELETE CASCADE,
  book_id    VARCHAR(20)  NOT NULL REFERENCES book (book_id) ON DELETE CASCADE,
  rating     SMALLINT     NOT NULL CHECK (rating BETWEEN 1 AND 5),
  content    VARCHAR(300) NOT NULL,
  created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_review_once UNIQUE (member_no, book_id)
);
CREATE INDEX idx_review_book ON review (book_id);

-- ---------------------------------------------------------
-- Supabase 보안: 이 앱은 자바(JDBC)로만 접속해요.
-- Supabase가 자동으로 여는 REST API(anon 키)로는 아무것도 읽고 쓰지 못하게 RLS를 켜 둬요.
-- (테이블 주인 postgres 계정으로 접속하는 자바 앱에는 영향이 없어요)
-- ---------------------------------------------------------
ALTER TABLE member     ENABLE ROW LEVEL SECURITY;
ALTER TABLE book       ENABLE ROW LEVEL SECURITY;
ALTER TABLE coupon     ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders     ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_item ENABLE ROW LEVEL SECURITY;
ALTER TABLE wishlist   ENABLE ROW LEVEL SECURITY;
ALTER TABLE review     ENABLE ROW LEVEL SECURITY;

