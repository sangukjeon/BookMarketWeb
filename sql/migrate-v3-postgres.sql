CREATE TABLE IF NOT EXISTS member_address (
  address_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_no     BIGINT       NOT NULL REFERENCES member (member_no) ON DELETE CASCADE,
  label         VARCHAR(20)  NOT NULL,
  receiver_name VARCHAR(50)  NOT NULL,
  phone         VARCHAR(20)  NOT NULL,
  address       VARCHAR(200) NOT NULL,
  is_default    BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_addr_member ON member_address (member_no);

CREATE TABLE IF NOT EXISTS member_coupon (
  member_no     BIGINT      NOT NULL REFERENCES member (member_no) ON DELETE CASCADE,
  code          VARCHAR(20) NOT NULL REFERENCES coupon (code) ON DELETE CASCADE,
  registered_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (member_no, code)
);

CREATE TABLE IF NOT EXISTS cart_item (
  member_no  BIGINT      NOT NULL REFERENCES member (member_no) ON DELETE CASCADE,
  book_id    VARCHAR(20) NOT NULL REFERENCES book (book_id) ON DELETE CASCADE,
  quantity   INT         NOT NULL,
  updated_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (member_no, book_id)
);

